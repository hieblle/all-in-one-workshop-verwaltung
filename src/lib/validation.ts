// Zod schemas for API boundaries (routes, server actions, webhooks).

const leerZuUndefined = (v: unknown) =>
  typeof v === "string" && v.trim() === "" ? undefined : v;

const optionalerText = z.preprocess(
  leerZuUndefined,
  z.string().trim().max(500).optional(),
);
const langerText = z.preprocess(
  leerZuUndefined,
  z.string().trim().max(10000).optional(),
);
// Links are clicked by team and trainers — only http(s), never javascript: etc.
const optionaleUrl = z.preprocess(
  leerZuUndefined,
  z.url({ protocol: /^https?$/ }).optional(),
);
const optionalesDatum = z.preprocess(
  leerZuUndefined,
  z.coerce.date().optional(),
);

// Workshop dates: a day plus start/end time, defaulting to 09:00–17:00 (SPEC §6).
const optionalerTag = z.preprocess(
  leerZuUndefined,
  z.string().regex(/^\d{4}-\d{2}-\d{2}$/, "Datum im Format JJJJ-MM-TT").optional(),
);
const optionaleUhrzeit = z.preprocess(
  leerZuUndefined,
  z.string().regex(/^\d{2}:\d{2}$/, "Uhrzeit im Format HH:MM").optional(),
);

function alsTermin(
  tag: string | undefined,
  von: string | undefined,
  bis: string | undefined,
): { start: Date | undefined; ende: Date | undefined } {
  if (!tag) return { start: undefined, ende: undefined };
  // Interpreted in the server's local time zone (Europe/Vienna).
  return {
    start: new Date(`${tag}T${von ?? STANDARD_BEGINN}:00`),
    ende: new Date(`${tag}T${bis ?? STANDARD_ENDE}:00`),
  };
}

