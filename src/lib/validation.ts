export const idSchema = z.coerce.number().int().positive();
const optionaleId = z.preprocess(leerZuUndefined, idSchema.optional());

export const workshopFormSchema = z
  .object({
    name: z.string().trim().min(1).max(200),
    kundeId: optionaleId,
    neueFirma: optionalerText,
    ansprechperson: optionalerText,
    type: z.enum(workshopTypeEnum.enumValues),
    format: z.preprocess(
      leerZuUndefined,
      z.enum(workshopFormatEnum.enumValues).optional(),
    ),
    modus: z.preprocess(
      leerZuUndefined,
      z.enum(workshopModusEnum.enumValues).optional(),
    ),
    ort: optionalerText,
    status: z.enum(workshopStatusEnum.enumValues).default("Vorabstimmung"),
    verantwortlichInternId: optionaleId,
    termin1: optionalerTag,
    termin1Von: optionaleUhrzeit,
    termin1Bis: optionaleUhrzeit,
    termin2: optionalerTag,
    termin2Von: optionaleUhrzeit,
    termin2Bis: optionaleUhrzeit,
    terminFup: optionalerTag,
    terminFupVon: optionaleUhrzeit,
    terminFupBis: optionaleUhrzeit,
    wsBetrag: z.preprocess(
      leerZuUndefined,
      z
        .string()
        .trim()
        .regex(/^\d+([.,]\d{1,2})?$/, "Betrag im Format 1234.56")
        .transform((v) => v.replace(",", "."))
        .optional(),
    ),
    sharepointUrl: optionaleUrl,
    notionProjectUrl: optionaleUrl,
    formsVorabUrl: optionaleUrl,
    formsFeedbackUrl: optionaleUrl,
    teamsMeetingUrl: optionaleUrl,
    verwendetesSlidedeck: optionaleUrl,
    sevdeskId: optionalerText,
    interneNotizen: langerText,
  })
  .refine((d) => d.kundeId !== undefined || d.neueFirma !== undefined, {
    message: "Kunde auswählen oder neue Firma angeben",
    path: ["kundeId"],
  })
  .transform(({ termin1Von, termin1Bis, termin2Von, termin2Bis, terminFupVon, terminFupBis, ...d }) => {
    const t1 = alsTermin(d.termin1, termin1Von, termin1Bis);
    const t2 = alsTermin(d.termin2, termin2Von, termin2Bis);
    const fup = alsTermin(d.terminFup, terminFupVon, terminFupBis);
    return {
      ...d,
      termin1: t1.start,
      termin1Ende: t1.ende,
      termin2: t2.start,
      termin2Ende: t2.ende,
      terminFup: fup.start,
      terminFupEnde: fup.ende,
    };
  })
  .refine(
    (d) =>
      [
        [d.termin1, d.termin1Ende],
        [d.termin2, d.termin2Ende],
        [d.terminFup, d.terminFupEnde],
      ].every(([start, ende]) => !start || !ende || ende > start),
    { message: "Ende muss nach dem Beginn liegen", path: ["termin1Bis"] },
  );

